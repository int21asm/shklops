import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { formatMoney } from "../shared/currency.js";
const url = process.env.TEST_URL || "http://localhost:3002";
mkdirSync("test-results", { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox"] });
try {
  const context = await browser.newContext({ timezoneId: "Asia/Jerusalem", viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage(), errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(url);
  await page.getByRole("button", { name: "כניסה להדגמה עם נתונים לדוגמה" }).click();
  await page.getByRole("heading", { name: "הכסף שלכם, בתמונה אחת." }).waitFor();
  const fixture = await page.evaluate(() => fetch("/api/data").then((r) => r.json()));
  const bankAccount = fixture.accounts.find((account) => account.provider === "hapoalim");
  const cardAccount = { ...fixture.accounts.find((account) => account.provider === "max"), provider: "visaCal" };
  fixture.accounts = [bankAccount, cardAccount];
  fixture.connections = fixture.connections.map((connection) => connection.id === cardAccount.connection_id ? { ...connection, provider: "visaCal" } : connection);
  const bank = (id, description, amount, date, extra = {}) => ({ id, account_id: bankAccount.id, connection_id: bankAccount.connection_id, account_number: bankAccount.number, provider: "hapoalim", description, amount, date, status: "completed", currency: "ILS", category: "כללי", ...extra });
  const card = (id, description, amount, category) => ({ id, account_id: cardAccount.id, connection_id: cardAccount.connection_id, account_number: cardAccount.number, provider: "visaCal", description, amount, date: "2026-10-17", processed_date: "2026-11-02", status: "completed", currency: "ILS", category, category_source: "chatgpt", category_description: description });
  fixture.transactions = [bank("salary", "משכורת", 1900000, "2026-11-01"), bank("mortgage", "טפחות - לווים", -666730, "2026-11-10"), bank("settlement", "הרשאה כאל", -1276107, "2026-11-02"),
    card("transport", "שירותי תחבורה", -423193, "תחבורה"), card("food", "קניות מזון", -256551, "מזון וקניות"), card("house", "שירותי בית", -596363, "בית וחשבונות"),
    bank("oct-salary", "משכורת", 2000000, "2026-10-01"), bank("oct-mortgage", "טפחות - לווים", -666730, "2026-10-10")];
  await page.route("**/api/data", (route) => route.fulfill({ json: fixture }));
  await page.clock.install({ time: new Date("2026-11-20T12:00:00Z") });
  await page.reload();
  const panel = page.getByRole("region", { name: "לאן הכסף זורם", exact: true });
  await panel.locator(".money-flow-income").filter({ hasText: formatMoney(1900000) }).waitFor();
  assert.equal(await panel.locator(".money-flow-expense").textContent(), formatMoney(1942837));
  assert.equal(await panel.locator(".money-flow-negative").textContent(), formatMoney(-42837));
  assert.equal(await panel.locator('.money-flow-node[data-node="cards"]').getAttribute("data-value"), "1276107");
  const expenseEdges = await panel.locator('.money-flow-link[data-source="hub"]').evaluateAll((links) => links.reduce((sum, link) => sum + Number(link.dataset.value), 0));
  assert.equal(expenseEdges, 1942837, "card categories must not be counted as additional bank expenses");
  const transport = panel.locator('.money-flow-node[data-node="card-category:תחבורה"]');
  await transport.locator(".money-flow-node-label").hover();
  await panel.getByRole("tooltip").getByText("תחבורה", { exact: true }).waitFor();
  const detail = panel.getByRole("region", { name: "פירוט זרימה: תחבורה", exact: true });
  assert.equal(await detail.locator("li").count(), 1);
  assert.equal(await detail.locator(".money-flow-detail-total").textContent(), formatMoney(423193));
  assert.equal(await detail.locator("li").getAttribute("data-transaction-id"), "transport");
  assert.match(await detail.textContent(), /חיוב בבנק:.*02.11.2026/);
  await panel.screenshot({ path: "test-results/sankey-desktop.png", animations: "disabled" });
  await panel.getByRole("button", { name: "סגירת פירוט הזרימה", exact: true }).click();
  await page.getByRole("button", { name: "הסתרת סכומים", exact: true }).click();
  await transport.focus();
  assert.equal(await panel.locator(".money-flow-income").textContent(), "••••••");
  assert.ok(!(await panel.getByRole("tooltip").textContent()).includes("₪"));
  assert.ok(!(await panel.locator(".money-flow-details").textContent()).includes("₪"));
  await page.getByRole("button", { name: "הצגת סכומים", exact: true }).click();
  await panel.getByLabel("חודש התרשים").selectOption("2026-10");
  assert.equal(await panel.locator(".money-flow-income").textContent(), formatMoney(2000000));
  assert.equal(await panel.locator(".money-flow-expense").textContent(), formatMoney(666730));
  assert.equal(await panel.locator(".money-flow-positive").textContent(), formatMoney(1333270));
  assert.equal(await panel.locator(".money-flow-details").count(), 0);
  assert.equal(await panel.locator('.money-flow-node[data-node="cards"]').count(), 0);
  await panel.getByLabel("חודש התרשים").selectOption("2026-11");
  fixture.transactions.find((row) => row.id === "house").amount = -500000;
  await page.reload();
  await panel.locator('.money-flow-node[data-node="unmatched"]').waitFor();
  assert.equal(await panel.locator('.money-flow-node[data-node="unmatched"]').getAttribute("data-value"), "1276107");
  assert.equal(await panel.locator('.money-flow-node[data-node^="card-category:"]').count(), 0);
  assert.equal(await panel.locator(".money-flow-expense").textContent(), formatMoney(1942837));
  await panel.locator('.money-flow-node[data-node="unmatched"]').focus();
  assert.match(await panel.locator(".money-flow-details").textContent(), /לא נמצא פירוט כרטיסים/);
  await page.setViewportSize({ width: 390, height: 844 });
  await panel.scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  assert.ok(await panel.locator(".money-flow-scroll").evaluate((element) => element.scrollWidth > element.clientWidth));
  await panel.screenshot({ path: "test-results/sankey-mobile.png", animations: "disabled" });
  fixture.transactions = fixture.transactions.filter((row) => row.provider === "visaCal");
  await page.reload();
  await panel.getByRole("heading", { name: "אין תנועות בנק שהושלמו בחודש הזה" }).waitFor();
  assert.equal(await panel.locator(".money-flow-svg").count(), 0);
  assert.deepEqual(errors, []);
  console.log("PASS: Sankey exact bank totals, matched category drilldown, no card double-counting, October/November selection, unmatched payments, amount privacy, mobile scrolling and bank-empty state");
  await context.close();
} finally { await browser.close(); }
